// Dev tool: screenshots of menu screens and the left-handed layout (BW_URL must point at a server).
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const OUT = 'test-results/screens';
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 860, height: 400 }, hasTouch: true });
await ctx.addInitScript(() => localStorage.setItem('blockwild.settings.v1', JSON.stringify({ controlsMode: 'touch', renderDistance: 3, quality: 'custom', tutorialDone: true, leftHanded: true })));
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(process.env.BW_URL);
await page.waitForFunction(() => document.querySelector('.menu-main'));
await page.waitForTimeout(6000);
await page.screenshot({ path: `${OUT}/menu.png` });
await page.click('text=Settings');
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/settings-graphics.png` });
await page.click('.tabs button:has-text("Controls")');
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/settings-controls.png` });
await page.click('[aria-label="Back"]');
await page.click('text=New World');
await page.click('summary');
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/create.png` });
await page.click('text=Create & Play');
await page.waitForFunction(() => window.__blockwild?.state === 'playing', null, { timeout: 90000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/left-handed.png` });
console.log('errors:', errors.join(' | ') || 'none');
await browser.close();
