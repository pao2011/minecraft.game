import { chromium } from 'playwright';
const S = process.argv[2];
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 800, height: 400 }, hasTouch: true });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => { if (!m.text().includes('[vite]')) logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}\n${e.stack}`));
await page.addInitScript(() => localStorage.setItem('blockwild.settings.v1', JSON.stringify({ controlsMode: 'touch', renderDistance: 3, quality: 'custom', tutorialDone: true })));
await page.goto('http://localhost:5173/');
await page.waitForFunction(() => document.querySelector('.menu-main'));
await page.click('text=New World');
await page.fill('input.text-input >> nth=1', 'explore-2');
await page.click('text=Create & Play');
await page.waitForFunction(() => window.__blockwild?.state === 'playing', null, { timeout: 90000, polling: 500 });
await page.evaluate(() => {
  const g = window.__blockwild.game;
  const inv = g.player.inventory;
  inv.set(0, { id: 'oak_log', count: 12 }); inv.set(1, { id: 'cobblestone', count: 30 }); inv.set(2, { id: 'stone_pickaxe', count: 1, damage: 40 }); inv.set(3, { id: 'torch', count: 16 }); inv.set(4, { id: 'bread', count: 5 }); inv.set(10, { id: 'iron_ingot', count: 7 }); inv.set(11, { id: 'stick', count: 9 });
});
await page.waitForTimeout(500);
await page.screenshot({ path: `${S}/x1-hud.png` });
await page.tap('.t-inv');
await page.waitForTimeout(400);
await page.screenshot({ path: `${S}/x2-inventory.png` });
await page.click('.tabs button:has-text("Crafting")');
await page.waitForTimeout(300);
await page.screenshot({ path: `${S}/x3-crafting.png` });
await page.click('.panel-head .icon-btn');
await page.waitForTimeout(300);
// Night + torch scene
await page.evaluate(() => { const g = window.__blockwild.game; g.record.time.tod = 0.78; const p = g.player; p.pitch = -0.5; });
await page.waitForTimeout(800);
await page.screenshot({ path: `${S}/x4-night.png` });
logs.push(JSON.stringify(await page.evaluate(() => ({ state: window.__blockwild.state, owners: window.__blockwild.input.owners.size }))));
console.log(logs.join('\n'));
await browser.close();
