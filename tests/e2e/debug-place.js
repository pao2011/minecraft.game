import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 900, height: 420 }, hasTouch: true });
await ctx.addInitScript(() => localStorage.setItem('blockwild.settings.v1', JSON.stringify({ controlsMode: 'touch', renderDistance: 3, quality: 'custom', tutorialDone: true })));
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('ERR', e.message));
await page.goto(process.env.BW_URL || 'http://localhost:5173/');
await page.waitForFunction(() => document.querySelector('.menu-main'));
await page.click('text=New World');
await page.fill('.form input.text-input >> nth=1', 'e2e-alpha');
await page.click('text=Create & Play');
await page.waitForFunction(() => window.__blockwild?.state === 'playing', null, { timeout: 90000 });
await page.waitForTimeout(1500);
const r = await page.evaluate(async () => {
  const g = window.__blockwild.game;
  g.player.inventory.set(0, { id: 'cobblestone', count: 5 });
  g.player.selected = 0;
  g.player.pitch = -0.9;
  await new Promise((r) => setTimeout(r, 300));
  const t = g.interaction.target;
  const out = { target: t && { kind: t.kind, hit: t.hit && { x: t.hit.x, y: t.hit.y, z: t.hit.z, id: t.hit.id, place: t.hit.place, normal: t.hit.normal } }, pos: g.player.pos };
  g.interaction.handleUse(true);
  out.after = t?.hit ? g.world.getBlock(t.hit.place.x, t.hit.place.y, t.hit.place.z) : null;
  out.toasts = [...document.querySelectorAll('.toast')].map((e) => e.textContent);
  out.count = g.player.inventory.count('cobblestone');
  return out;
});
console.log(JSON.stringify(r, null, 1));
await browser.close();
